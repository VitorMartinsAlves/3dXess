export const SUPPORTED_LOCALES = ["pt-BR", "en", "es", "zh-CN"];
const resources = Object.fromEntries(SUPPORTED_LOCALES.map((locale) => [locale, {
  common: common[locale],
  home: home[locale],
  account: accountResources[locale],
}]));
const instances = new Map();

// The URL is the source of truth. A dedicated instance per locale prevents
// cross-locale state leaks while Next.js pre-renders routes concurrently.
export async function getLocaleI18n(locale = "pt-BR") {
  const language = SUPPORTED_LOCALES.includes(locale) ? locale : "pt-BR";
  if (!instances.has(language)) {
    const instance = createInstance();
    const initialized = instance.use(initReactI18next).init({
      resources, lng: language, fallbackLng: "pt-BR",
      supportedLngs: SUPPORTED_LOCALES,
      defaultNS: "common", ns: ["common", "home", "account"],
      interpolation: { escapeValue: false },
      returnEmptyString: false, initAsync: false,
    }).then(() => instance);
    instances.set(language, initialized);
  }
  return instances.get(language);
}
